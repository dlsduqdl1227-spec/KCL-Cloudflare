import assert from 'node:assert/strict';
import {createRpcFixture} from './helpers/rpc-fixture.mjs';
import {seedKcrStations,stationSubmission} from './helpers/kcr-station-fixture.mjs';
const api=await createRpcFixture();
const request=async(action,...args)=>(await api.handle({action,args})).json();
try{
 const {stations,judges}=await seedKcrStations(api),head=judges[0],other=judges[1];
 await api.rpc('submitScores',stationSubmission(head,stations[1],21));
 await api.rpc('updateCompetitionAdminSettings',{code:'KCR',currentRound:'결선',isActive:true},api.actor);
 const submission={...stationSubmission(head,stations[1],21),round:'결선'};
 submission.rows.forEach((r,i)=>Object.assign(r.extraFields,{'Flavor(플레이버)':3,'Aftertaste(에프터테이스트)':3,'Acidity(산미)':3,'Sweetness(단맛) ×2':3,'Mouthfeel(마우스필)':3,'Overall(오버롤)':3,'Flavor 스마트태그':'블루베리',종합코멘트:'결선 원본 '+i}));
 await api.rpc('submitScores',submission);
 await api.rpc('submitScores',{...submission,judgeToken:other.judgeToken});
 const original=api.db.prepare("SELECT * FROM scores WHERE competition_code='KCR' AND round='결선' AND judge_name=?").get(head.name);
 const unrelated=JSON.stringify(api.db.prepare('SELECT * FROM scores WHERE id<>? ORDER BY id').all(original.id));
 const settings=JSON.stringify(api.db.prepare('SELECT * FROM competitions ORDER BY code').all());
 const participants=JSON.stringify(api.db.prepare('SELECT * FROM participants ORDER BY id').all());
 // Old/open clients may still request returnedOnly: completed KCR finals must remain discoverable.
 const query={...head,round:'결선',returnedOnly:true,compactReview:true};
 let list=await api.rpc('getReviewList','KCR',query);
 assert.equal(list.list.length,2,'head sees both completed final cups without manager return');
 assert.ok(list.list.every(x=>x.finalWorkflow&&x.status==='평가완료'&&x.finalRevision&&x.round==='결선'));
 assert.doesNotMatch(JSON.stringify(list),/KCR QA 1|KCR QA 2/,'identities remain blind');
 const ci=list.headers.indexOf('종합코멘트');assert.ok(ci>=0);
 const target=list.list.find(x=>x.scoreRowId===original.id);
 const correction={competitionCode:'KCR',round:'결선',entries:[{rowIndex:target.rowIndex,revision:target.finalRevision,updates:{[ci]:'수정 코멘트'}}]};
 assert.equal((await request('resubmitFinalEvaluations',correction,other)).success,false,'other judge cannot edit head');
 assert.equal((await request('resubmitFinalEvaluations',{...correction,round:'예선'},head)).success,false,'round cannot change');
 assert.equal((await request('resubmitFinalEvaluations',{...correction,entries:[{...correction.entries[0],rowIndex:original.id+':99'}]},head)).success,false,'invalid cup rejected');
 assert.equal((await request('updateReviewRow','KCR',target.rowIndex,{[ci]:'unsafe'},'수정완료','',head)).success,false,'unguarded legacy writes stay blocked');
 await api.rpc('resubmitFinalEvaluations',correction,head);
 const saved=api.db.prepare('SELECT * FROM scores WHERE id=?').get(original.id);
 const before=JSON.parse(original.payload_json),after=JSON.parse(saved.payload_json);
 assert.equal(saved.total_score,original.total_score,'comment correction does not alter scores');
 assert.equal(after.rows[0].extraFields.종합코멘트,'수정 코멘트');
 assert.deepEqual(after.rows[1],before.rows[1],'other cup remains byte-for-byte equivalent');
 for(const key of Object.keys(before.rows[0].extraFields).filter(k=>k!=='종합코멘트'))assert.equal(String(after.rows[0].extraFields[key]),String(before.rows[0].extraFields[key]),key+' preserved');
 assert.equal((await request('resubmitFinalEvaluations',correction,head)).success,false,'stale/double save rejected');
 assert.equal((await request('submitScores',submission)).success,false,'duplicate final evaluation still rejected');
 list=await api.rpc('getReviewList','KCR',query);assert.equal(list.list.length,2,'saved evaluation stays visible');
 const fresh=list.list.find(x=>x.scoreRowId===original.id);
 assert.notEqual(fresh.finalRevision,target.finalRevision);
 const correction2={...correction,entries:[{rowIndex:fresh.rowIndex,revision:fresh.finalRevision,updates:{[ci]:'두 번째 수정'}}]};
 const concurrent=await Promise.all([request('resubmitFinalEvaluations',correction2,head),request('resubmitFinalEvaluations',correction2,head)]);
 assert.equal(concurrent.filter(x=>x.success).length,1,'concurrent corrections are atomic');
 assert.ok((await api.rpc('getRanking','KCR',api.actor,'결선')).ranking.length);
 const preview=await api.rpc('getAdminDebriefPreview','KCR',original.unit,'결선',api.actor);
 assert.ok(preview.scores.length);assert.match(JSON.stringify(preview),/두 번째 수정/);
 assert.equal(JSON.stringify(api.db.prepare('SELECT * FROM scores WHERE id<>? ORDER BY id').all(original.id)),unrelated,'preliminary and other judges untouched');
 assert.equal(JSON.stringify(api.db.prepare('SELECT * FROM competitions ORDER BY code').all()),settings);
 assert.equal(JSON.stringify(api.db.prepare('SELECT * FROM participants ORDER BY id').all()),participants);
 console.log('Stage256 KCR final own correction: visible submissions, preserved cups/tags/comments/locks/scores, ownership, round isolation, concurrency and ranking/debrief passed.');
}finally{api.close();}
