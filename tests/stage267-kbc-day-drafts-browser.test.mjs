import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRpcFixture} from './helpers/rpc-fixture.mjs';
import {createBrowserFixture,inspectPage} from './helpers/browser-fixture.mjs';
import {seedKbcTimetable} from './helpers/kbc-timetable-fixture.mjs';
const api=await createRpcFixture(),qa=await createBrowserFixture({apiHandler:api.handle});
fs.mkdirSync('tmp/stage267-qa',{recursive:true});
try {
  await seedKbcTimetable(api);
  const plan=await api.rpc('getKbcMainTimetablePlan',api.actor);
  await api.rpc('applyKbcMainTimetable',{revision:plan.revision},api.actor);
  await api.rpc('updateCompetitionAdminSettings',{code:'KBC',optionSettings:{kbcMainDay:'1'}},api.actor);
  const page=await qa.page(390,950);
  await page.goto(qa.origin+'/assessment/');
  await page.evaluate(a=>{_judge=a;loadAdminPanel();},api.actor);
  await page.locator('#admin-cfg-round-KBC-stage').waitFor({state:'attached'});
  assert.deepEqual(await page.locator('#admin-cfg-round-KBC-stage option').allTextContents(),['예선','본선 1일차','본선 2일차','결선']);
  await page.evaluate(a=>{hideOverlay();_judge=a;_selComp={code:'KBC',name:'KBC',currentRound:'본선',optionSettings:{kbcMainDay:'1'},isActive:true};startKbc();},api.actor);
  await page.waitForFunction(()=>participantListForCode_('KBC').length===20);
  assert.deepEqual(await page.locator('#kbc-main-day option').allTextContents(),['본선 1일차','본선 2일차']);
  assert.equal(await page.locator('#kbc-participant-select option').count(),11);
  await page.locator('#kbc-participant-select').selectOption('0');
  await page.locator('#kbc-comment').fill('1일차 김다정 의견');
  await page.evaluate(()=>{document.getElementById('kbc-presentation').value='4.2';kbcToggleTagValue_('service','Service Professionalism','1일차 태그');calcKbcTotal();kclSaveActiveEvalDraftNow_(true);});
  const day1Key=await page.evaluate(()=>kclDraftKey_('KBC'));
  await page.locator('#kbc-main-day').selectOption('2');
  assert.equal(await page.locator('#kbc-comment').inputValue(),'');
  assert.equal(await page.locator('#kbc-participant-select option').count(),11);
  assert.doesNotMatch(await page.locator('#kbc-participant-select').innerText(),/김다정/);
  await page.locator('#kbc-participant-select').selectOption('10');
  assert.equal(await page.locator('#kbc-presentation').inputValue(),'3');
  await page.locator('#kbc-comment').fill('2일차 최준호 의견');
  await page.evaluate(()=>kclSaveActiveEvalDraftNow_(true));
  const day2Key=await page.evaluate(()=>kclDraftKey_('KBC'));
  assert.notEqual(day1Key,day2Key);
  await page.locator('#kbc-main-day').selectOption('1');
  assert.equal(await page.locator('#kbc-comment').inputValue(),'1일차 김다정 의견');
  assert.equal(await page.locator('#kbc-presentation').inputValue(),'4.2');
  assert.deepEqual(await page.evaluate(()=>kbcCollectTagPayload_().service['Service Professionalism']),['1일차 태그']);
  await page.locator('#kbc-participant-select').selectOption('1');
  assert.equal(await page.locator('#kbc-comment').inputValue(),'','different players have independent drafts');
  await page.locator('#kbc-participant-select').selectOption('0');
  assert.equal(await page.locator('#kbc-comment').inputValue(),'1일차 김다정 의견');
  await page.reload();
  await page.evaluate(a=>{_judge=a;_selComp={code:'KBC',name:'KBC',currentRound:'본선',optionSettings:{kbcMainDay:'1'},isActive:true};startKbc();},api.actor);
  await page.waitForFunction(()=>document.getElementById('kbc-comment').value==='1일차 김다정 의견');
  await page.locator('#kbc-main-day').selectOption('2');
  assert.equal(await page.locator('#kbc-comment').inputValue(),'2일차 최준호 의견');
  assert.equal(await page.locator('#kbc-name').inputValue(),'최준호');
  assert.equal((await inspectPage(page)).pageOverflow,false);
  await page.screenshot({path:'tmp/stage267-qa/kbc-evaluation-mobile.png'});
  assert.deepEqual(page.qaErrors,[]);
  await page.goto(qa.origin+'/registry/');
  await page.evaluate(a=>{actor=a;document.getElementById('loginCard').classList.add('hidden');document.getElementById('main').classList.remove('hidden');loadRegistry();},api.actor);
  await page.waitForFunction(()=>document.querySelectorAll('#partTable [data-edit-part]').length===10);
  assert.match(await page.locator('#partTable').innerText(),/김다정/);
  assert.doesNotMatch(await page.locator('#partTable').innerText(),/최준호|예선만 참가/);
  await page.locator('#partTable [data-edit-part]').first().click();
  assert.equal(await page.locator('#mNo').inputValue(),'100','round-specific table numbers must not overwrite original participant IDs');
  assert.equal(await page.locator('#mMainPrep').inputValue(),'11:00~11:15');
  await page.locator('#participantCancelBtn').click();
  await page.locator('#kbc-roster-day2').click();
  assert.equal(await page.locator('#partTable [data-edit-part]').count(),10);
  assert.match(await page.locator('#partTable').innerText(),/최준호/);
  await page.locator('#kbc-roster-all').click();
  assert.equal(await page.locator('#partTable [data-edit-part]').count(),21);
  await page.locator('#kbc-roster-final').click();
  await page.waitForFunction(()=>document.getElementById('kbc-final-roster').textContent.includes('본선 평가 0/20명'));
  assert.equal(await page.locator('#partTable [data-edit-part]').count(),0);
  await page.locator('#kbc-roster-day1').click();
  await page.screenshot({path:'tmp/stage267-qa/kbc-roster-mobile.png'});
  assert.equal((await inspectPage(page)).pageOverflow,false);assert.deepEqual(page.qaErrors,[]);
  await page.setViewportSize({width:1440,height:1000});
  assert.equal((await inspectPage(page)).pageOverflow,false);
  await page.screenshot({path:'tmp/stage267-qa/kbc-roster-desktop.png'});
  console.log('Stage267: main day-only controls, day/player independent tags/scores/comments, rapid switching and reload, ten-player roster tabs, editable schedule, preserved IDs and responsive layout passed.');
}finally{await qa.close();api.close();}
